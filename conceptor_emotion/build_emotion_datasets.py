#!/usr/bin/env python3
"""
Emotion-specific datasets for fitting steering statistics (mu_e, mu_n, C_e).

Two sources, written to conceptor_emotion/data/:

  synthetic   emotion_pairs_synthetic.jsonl
              For each query, six replies with the SAME content that differ only in
              tone: neutral, joy, anger, disgust, fear, sadness. Generated by an OpenAI
              model (OPENAI_API_KEY in qwen_testing/.env). Minimal pairs make
              emotional - neutral activations isolate the emotion instead of content
              or prompt-position effects.

  goemotions  goemotions_emotion_texts.json
              Human-written Reddit comments from GoEmotions (EAS_validation/dataset_new)
              with exactly one label among the 27, for the five emotions plus neutral.
              Unpaired, but real text rather than model output.

Queries for the synthetic pairs are EmotionQuery+ [0, n_queries); evaluation uses
[300, ...), so the sets are disjoint.

Usage:
    python build_emotion_datasets.py --source goemotions
    python build_emotion_datasets.py --source synthetic --n_queries 250 --model gpt-5.5
"""

import argparse
import glob
import json
import random
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import pandas as pd
import requests

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent / "data"
TONES = ["neutral", "joy", "anger", "disgust", "fear", "sadness"]

PAIR_PROMPT = """A user asked an assistant: "{query}"

Write six replies that convey the SAME content (same points, same facts, similar length of 2-3 sentences, first person) and differ ONLY in emotional tone:
- neutral: calm, factual, flat; no emotional words at all
- joy, anger, disgust, fear, sadness: that emotion is INTENSE and saturates every sentence through vivid word choice, imagery and rhythm (exclamations, interjections where natural), so a reader would identify it instantly
Keep the facts identical across all six. Avoid naming the emotion itself (e.g. don't write "I feel sad"). Return JSON with keys neutral, joy, anger, disgust, fear, sadness."""


def openai_pairs(query, model, api_key):
    """One query -> dict of six same-content replies, or None after three failed tries."""
    for _ in range(3):
        try:
            r = requests.post("https://api.openai.com/v1/chat/completions", timeout=180,
                              headers={"Authorization": f"Bearer {api_key}"},
                              json={"model": model, "reasoning_effort": "low",
                                    "response_format": {"type": "json_object"},
                                    "messages": [{"role": "user", "content": PAIR_PROMPT.format(query=query)}]})
            if r.status_code == 429:
                time.sleep(10)
                continue
            rec = json.loads(r.json()["choices"][0]["message"]["content"])
            if all(isinstance(rec.get(t), str) and len(rec[t].split()) >= 5 for t in TONES):
                return {"query": query, **{t: rec[t].strip() for t in TONES}}
        except (requests.RequestException, ValueError, KeyError, IndexError):
            pass
    return None


def build_synthetic(n_queries, model, workers):
    sys.path.insert(0, str(ROOT))
    from env_config import require_env
    api_key = require_env("OPENAI_API_KEY")

    out_path = OUT / "emotion_pairs_synthetic.jsonl"
    queries = json.load(open(ROOT / "conceptor_emotion/EmotionQuery+.json"))[:n_queries]
    done = set()
    if out_path.exists():                                   # resume
        done = {json.loads(l)["query"] for l in open(out_path)}
    todo = [q for q in queries if q not in done]
    t0, n_new = time.time(), 0
    with open(out_path, "a") as f, ThreadPoolExecutor(workers) as pool:
        for i, rec in enumerate(pool.map(lambda q: openai_pairs(q, model, api_key), todo)):
            if rec:
                f.write(json.dumps({**rec, "generator": model}) + "\n")
                f.flush()
                n_new += 1
            if (i + 1) % 25 == 0:
                print(f"{i + 1}/{len(todo)}  ({time.time() - t0:.0f}s)", flush=True)
    print(f"wrote {n_new}/{len(todo)} new pairs -> {out_path}")


def build_goemotions(per_emotion, seed):
    files = glob.glob(str(ROOT / "EAS_validation/dataset_new/goemotions_*_*.csv"))
    df = pd.concat(pd.read_csv(f) for f in files)
    label_cols = list(df.columns[df.columns.get_loc("example_very_unclear") + 1:])
    df = df[~df.example_very_unclear]
    single = df[df[label_cols].sum(axis=1) == 1]
    rng = random.Random(seed)
    data = {}
    for t in TONES:
        texts = single.loc[single[t] == 1, "text"].drop_duplicates()
        texts = [s.strip() for s in texts if 6 <= len(s.split()) <= 60 and "[NAME]" not in s]
        rng.shuffle(texts)
        data[t] = texts[:per_emotion]
        print(f"{t:8s} {len(texts):6d} available, kept {len(data[t])}")
    path = OUT / "goemotions_emotion_texts.json"
    json.dump(data, open(path, "w"), indent=1)
    print(f"wrote {path}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", choices=["synthetic", "goemotions"], required=True)
    ap.add_argument("--n_queries", type=int, default=200)
    ap.add_argument("--model", default="gpt-5.5")
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--per_emotion", type=int, default=400)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    OUT.mkdir(exist_ok=True)
    if args.source == "synthetic":
        build_synthetic(args.n_queries, args.model, args.workers)
    else:
        build_goemotions(args.per_emotion, args.seed)


if __name__ == "__main__":
    main()
